// Builds data/zip/{first3}.json from the Census ZCTA Gazetteer (public domain).
// Usage:
//   node scripts/build-zip-index.mjs            # downloads the 2024 gazetteer zip
//   node scripts/build-zip-index.mjs path.txt   # uses an already-extracted gazetteer .txt
//
// Each output file maps a 5-digit ZCTA to [lat, lon] (4 decimals), so the site loads
// one small file per lookup. ZCTAs approximate ZIP codes; some PO-box ZIPs are absent.

import { mkdirSync, writeFileSync, readFileSync, readdirSync, unlinkSync, existsSync } from 'node:fs';
import { inflateRawSync } from 'node:zlib';
import path from 'node:path';

const SOURCE_URL = 'https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2024_Gazetteer/2024_Gaz_zcta_national.zip';
const OUT_DIR = path.resolve('data/zip');

async function loadText() {
  const arg = process.argv[2];
  if (arg) return readFileSync(arg, 'utf8');
  console.log('Downloading', SOURCE_URL);
  const res = await fetch(SOURCE_URL);
  if (!res.ok) throw new Error(`Download failed: HTTP ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  return unzipSingleEntry(buf).toString('utf8');
}

// Minimal reader for a single-entry .zip (deflate). Reads the central directory
// to find the entry, then inflates the local file data.
function unzipSingleEntry(buf) {
  const eocd = buf.lastIndexOf(Buffer.from([0x50, 0x4b, 0x05, 0x06]));
  if (eocd < 0) throw new Error('Not a zip file');
  const cdOffset = buf.readUInt32LE(eocd + 16);
  if (buf.readUInt32LE(cdOffset) !== 0x02014b50) throw new Error('Central directory not found');
  const method = buf.readUInt16LE(cdOffset + 10);
  const csize = buf.readUInt32LE(cdOffset + 20);
  const localOffset = buf.readUInt32LE(cdOffset + 42);
  if (buf.readUInt32LE(localOffset) !== 0x04034b50) throw new Error('Local header not found');
  const nameLen = buf.readUInt16LE(localOffset + 26);
  const extraLen = buf.readUInt16LE(localOffset + 28);
  const dataStart = localOffset + 30 + nameLen + extraLen;
  const data = buf.subarray(dataStart, dataStart + csize);
  if (method === 0) return data;
  if (method === 8) return inflateRawSync(data);
  throw new Error(`Unsupported zip method ${method}`);
}

function parseGazetteer(text) {
  const lines = text.split(/\r?\n/).filter(Boolean);
  const header = lines[0].split('\t').map((h) => h.trim());
  const iGeo = header.indexOf('GEOID');
  const iLat = header.indexOf('INTPTLAT');
  const iLon = header.indexOf('INTPTLONG');
  if (iGeo < 0 || iLat < 0 || iLon < 0) throw new Error(`Unexpected columns: ${header.join(', ')}`);
  const byPrefix = new Map();
  for (const line of lines.slice(1)) {
    const cols = line.split('\t');
    const zip = cols[iGeo].trim();
    if (!/^\d{5}$/.test(zip)) continue;
    const lat = Number(Number(cols[iLat]).toFixed(4));
    const lon = Number(Number(cols[iLon]).toFixed(4));
    const prefix = zip.slice(0, 3);
    if (!byPrefix.has(prefix)) byPrefix.set(prefix, {});
    byPrefix.get(prefix)[zip] = [lat, lon];
  }
  return byPrefix;
}

const text = await loadText();
const byPrefix = parseGazetteer(text);
mkdirSync(OUT_DIR, { recursive: true });
if (existsSync(OUT_DIR)) for (const f of readdirSync(OUT_DIR)) if (f.endsWith('.json')) unlinkSync(path.join(OUT_DIR, f));
let total = 0;
for (const [prefix, table] of byPrefix) {
  writeFileSync(path.join(OUT_DIR, `${prefix}.json`), JSON.stringify(table));
  total += Object.keys(table).length;
}
writeFileSync(path.join(OUT_DIR, 'README.md'), [
  '# ZIP to coordinates',
  '',
  'Generated by `scripts/build-zip-index.mjs` from the U.S. Census Bureau 2024 ZCTA Gazetteer (public domain).',
  `Source: ${SOURCE_URL}`,
  '',
  'Each `NNN.json` maps 5-digit ZCTAs starting with `NNN` to `[latitude, longitude]` (internal point).',
  'ZCTAs approximate ZIP codes; some PO-box-only ZIPs are absent and will read as "ZIP not found".',
  '',
].join('\n'));
console.log(`Wrote ${byPrefix.size} files covering ${total} ZCTAs to ${OUT_DIR}`);
